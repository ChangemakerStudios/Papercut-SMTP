/**
 * Opens a url in a new tab through a target="_blank" link instead of window.open().
 * The desktop shell's macOS webview never surfaces window.open(), but it does report
 * _blank links, which the shell hands to the default browser. Browsers treat both the same.
 */
export function openInNewTab(url: string): void {
  const link = document.createElement('a');
  link.href = url;
  link.target = '_blank';
  link.rel = 'noopener noreferrer';
  link.style.display = 'none';
  document.body.appendChild(link);
  link.click();
  link.remove();
}
